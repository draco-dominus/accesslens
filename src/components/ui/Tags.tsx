import type { Finding } from "@/lib/analysis-schema";
import { STATUS_LABEL } from "@/lib/session/lumi";
import type { FindingStatus } from "@/lib/session/types";
import { Alert, Check } from "./Icons";

/**
 * Tags adapted from the prototype's Severity.tsx. The real backend reports the AI's confidence
 * (not a severity), so that's what we show; status reflects later scans.
 */

type BarrierType = Finding["barrierType"];

const TYPE_LABEL: Record<BarrierType, string> = {
  steps: "Steps or level change",
  obstructed_walkway: "Obstructed path",
  protruding_obstacle: "Protruding object",
  other: "Other barrier",
};
export const barrierTypeLabel = (t: BarrierType) => TYPE_LABEL[t];

export function TypeTag({ type }: { type: BarrierType }) {
  return (
    <span className="inline-flex items-center rounded-full bg-surface-2 px-2.5 py-1 text-[13px] leading-none font-semibold text-fg">
      {TYPE_LABEL[type]}
    </span>
  );
}

export function ConfidenceTag({ confidence }: { confidence: "low" | "medium" | "high" }) {
  return (
    <span className="inline-flex items-center rounded-full border border-line px-2.5 py-1 text-[13px] leading-none font-medium text-muted">
      {confidence[0].toUpperCase() + confidence.slice(1)} confidence
    </span>
  );
}

/** Status across scans. Never uses color alone: each has an icon or text. */
export function StatusTag({ status }: { status: FindingStatus }) {
  if (status === "appears_improved") {
    return (
      <span className="inline-flex items-center gap-1 rounded-full bg-[color-mix(in_srgb,var(--color-success)_16%,transparent)] px-2.5 py-1 text-[13px] leading-none font-semibold text-fg">
        <Check size={13} strokeWidth={2.8} className="text-success" />
        {STATUS_LABEL[status]}
      </span>
    );
  }
  if (status === "needs_verification") {
    return (
      <span className="inline-flex items-center gap-1 rounded-full bg-[color-mix(in_srgb,var(--color-caution)_16%,transparent)] px-2.5 py-1 text-[13px] leading-none font-semibold text-fg">
        <span aria-hidden className="text-[12px] font-bold text-caution">?</span>
        {STATUS_LABEL[status]}
      </span>
    );
  }
  if (status === "still_observed") {
    return (
      <span className="inline-flex items-center gap-1 rounded-full border border-line px-2.5 py-1 text-[13px] leading-none font-semibold text-fg">
        <Alert size={13} className="text-alert" />
        {STATUS_LABEL[status]}
      </span>
    );
  }
  return (
    <span className="inline-flex items-center gap-1.5 rounded-full border border-line px-2.5 py-1 text-[13px] leading-none font-semibold text-fg">
      <span aria-hidden className="size-2 rounded-full bg-caution" />
      {STATUS_LABEL[status]}
    </span>
  );
}

/** Marks that observations are AI-generated (real analysis, not demo content). */
export function AiBadge({ className = "" }: { className?: string }) {
  return (
    <span
      title="Observations generated by AI from your photos. Check them in person."
      className={`iri-conic inline-flex shrink-0 items-center rounded-full px-2.5 py-1 text-[12px] leading-none font-semibold tracking-[0.02em] text-black ${className}`}
    >
      AI observations
      <span className="sr-only">: generated by AI from your photos. Check them in person.</span>
    </span>
  );
}
